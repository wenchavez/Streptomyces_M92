#FUNCTIONS
def obtener_smiles_antismash(archivo):
    #Retrieves the SMILES string generated by antiSMASH (if any)
    #Returns None if it does not exist

    with open(archivo, encoding="utf-8") as f:
        texto = f.read()

    if '/SMILES="' not in texto:
        return None

    smiles = texto.split('/SMILES="', 1)[1]
    smiles = smiles.split('"', 1)[0]

    return smiles.replace(" ", "").replace("\n", "")

def evaluar_smiles(smiles):
    #Classify a SMILES string as: unavailable, invalid, partial, complete

    if not smiles:
        return "Unavailable"
    
    mol =  Chem.MolFromSmiles(smiles) 

    if mol is None:
        return "Invalid"

    if "[*]" in smiles:
        return "Partial"

    return "Complete"

def leer_prism(archivo):
    #Extract SMILES scaffolds generated by PRISM

    scaffolds = []

    if not archivo.exists():
        return scaffolds

    with open(archivo, encoding="utf-8") as f:
        for linea in f:
            partes = linea.strip().split("\t")

            if len(partes) < 2:
                continue

            nombre = partes[0].lstrip(",")
            smiles = partes[1].strip()

            scaffolds.append((nombre, smiles))

    return scaffolds

def obtener_archivo_prism(region):
    #Search for the PRISM results file
    numero_region = region.split(".")[-1]
    archivo = ruta_prism / f"SMILES_{numero_region}_prism.txt"
    return archivo

#Analysis of a Region
def analizar_region(region):

    print("\n" + "=" * 60)
    print(region)
    print("=" * 60)

    #antiSMASH

    archivo_gbk = ruta_antismash / f"{region}.gbk"
    smiles_anti = obtener_smiles_antismash(archivo_gbk)

    #PRISM

    archivo_prism = obtener_archivo_prism(region)
    print("\n[1] PRISM")
    print(f"Archivo: {archivo_prism}")

    if archivo_prism.exists():
        scaffolds = leer_prism(archivo_prism)

        if scaffolds:
            print(f"PRISM: {len(scaffolds)} scaffold(s) encontrado(s)")

            resultados = []

            for nombre, smiles in scaffolds:
                estado = evaluar_smiles(smiles)
                print(f"  {nombre}: {estado}")

                resultados.append({
                    "nombre": nombre,
                    "smiles": smiles,
                    "estado": estado
                })

        #If PRISM has a complete structure
            completos = [r for r in resultados if r["estado"] == "Complete"]
             
            if completos:
                print("\n Path: PRISM → RDKit")

                return [
                    {
                        "Region": region,
                        "Source": "PRISM",
                        "Status": "Complete",
                        "Next Step": "RDKit",
                        "SMILES": r["smiles"],
                        "Scaffolds": r["nombre"]
                    }
                    for r in completos
                ]
    #PRISM has incomplete structures
            else:
                print("\n PRISM did not generate a complete structure")
                print("Moving on to analyze the SMILES string generated by antiSMASH")

    #antiSMASH
    print("\n[2] antiSMASH")

    archivo_gbk = ruta_antismash/f"{region}.gbk"

    print(f"Archivo: {archivo_gbk}")

    smiles_anti = obtener_smiles_antismash(archivo_gbk)
    estado_anti = evaluar_smiles(smiles_anti)

    print(f"antiSMASH: {estado_anti}")


    #antiSMASH complete
    if estado_anti == "Complete":
        print("\n Path: antiSMASH to RDKit")

        return[{
            "Region": region,
            "Source": "antiSMASH",
            "Status": "Complete",
            "Next Step": "RDKit",
            "SMILES": smiles_anti,
            "Scaffolds": 1
        }]
    

    #antiSMASH partial
    elif estado_anti == "Partial":
        print("\n antiSMASH structure partial")
        print("Path: MIBiG Homology")

        return[{
            "Region": region,
            "Source": "antiSMASH",
            "Status": "Partial",
            "Next Step": "MIBiG",
            "SMILES": smiles_anti,
            "Scaffolds": 0
        }]
    
    #antiSMASH without structures 
    else:
        print("\n antiSMASH does not provide a structure")
        print("Path: MIBiG")

        return[{
            "Region": region,
            "Source": "antiSMASH",
            "Status": "Partial",
            "Next Step": "MIBiG",
            "SMILES": "",
            "Scaffolds": 0
        }]

